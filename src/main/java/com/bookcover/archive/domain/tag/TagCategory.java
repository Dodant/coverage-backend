package com.bookcover.archive.domain.tag;

/**
 * 디자인 태그 카테고리.
 * 태그를 스타일, 색상, 레이아웃, 타이포그래피, 일러스트레이션 등으로 분류합니다.
 */
public enum TagCategory {
    /** 디자인 스타일 (미니멀, 레트로 등) */
    STYLE,
    /** 색상 관련 태그 */
    COLOR,
    /** 레이아웃 관련 태그 */
    LAYOUT,
    /** 타이포그래피 관련 태그 */
    TYPOGRAPHY,
    /** 일러스트레이션 관련 태그 */
    ILLUSTRATION
}
